# Protein chains of an assembly

@dataclass
class ChainSelectionStats:
    protein_instances: int = 0
    copies_skipped: int = 0
    # Chains grouped by their name because _pdbx_chain_remapping did not cover them.
    remap_fallback: int = 0
    unnamed: int = 0
    duplicate_names: int = 0
    full_scan: bool = False
    # _pdbx_poly_seq_scheme had to go through biotite.
    slow_path: bool = False


def _read_remapping(category_lines: CategoryLines | None) -> dict[str, tuple[str, bool]] | None:
    """assembly label_asym_id -> (original label_asym_id, carries the original auth name)."""
    if category_lines is None:
        return None
    category = parse_category('pdbx_chain_remapping', category_lines)
    if any(column not in category for column in _REMAP_COLUMNS):
        return None
    labels, auths, orig_labels, orig_auths = (category_column(category, column) for column in _REMAP_COLUMNS)
    return {
        label: (orig_label, auth == orig_auth)
        for label, auth, orig_label, orig_auth in zip(labels, auths, orig_labels, orig_auths)
    }


def select_protein_chains(
        rows: Iterable[tuple[str, ...]],
        protein_entities: set[str],
        remapping: dict[str, tuple[str, bool]] | None,
        stats: ChainSelectionStats | None = None,
        residue_ids: bool = False) -> tuple[dict, ChainSelectionStats]:
    """Observed sequences of the protein chains, one instance per chain of the deposited entry.

    `rows` are (asym_id, entity_id, seq_id, mon_id, pdb_mon_id, pdb_strand_id) tuples of
    `_pdbx_poly_seq_scheme` - with residue_ids, followed by pdb_seq_num and pdb_ins_code, and the
    result maps each chain to (sequence, {residue id: sequence position 1..n}), the residue id
    being the author number with the insertion code appended ('52', '52A'), as the PDB format
    parsers write it. Symmetry copies share coordinates (up to a rigid transformation)
    and sequence with the chain they were made from, so only one instance of every original
    chain is kept: the one that carries the original name if there is one, else the first.
    Which instances those are is decided at the first row of each chain, so the residues of
    the skipped copies are never collected - 1m4x-assembly1 keeps 3 of its 5040 chains.

    A residue is observed when `pdb_mon_id` is set. Microheterogeneity gives several rows for one
    seq_id; the first observed one counts.
    """
    if stats is None:
        stats = ChainSelectionStats()

    representative: dict[tuple[str, str], str] = {}        # group -> asym_id
    representative_is_original: dict[tuple[str, str], bool] = {}
    group_order: list[tuple[str, str]] = []
    strand_of: dict[str, str] = {}
    residues: dict[str, dict[int, str]] = {}
    collect: dict[str, bool] = {}                           # asym_id -> its rows are collected

    for asym_id, entity_id, seq_id, mon_id, pdb_mon_id, strand_id, *residue in rows:
        keep = collect.get(asym_id)
        if keep is None:
            # First row of a chain: decide once whether it is the instance to keep.
            if entity_id not in protein_entities:
                collect[asym_id] = False
                continue
            stats.protein_instances += 1
            remapped = None if remapping is None else remapping.get(asym_id)
            if remapped is not None:
                group = ('label', remapped[0])
                is_original = remapped[1]
            else:
                stats.remap_fallback += 1
                group = ('auth', strand_id.split('-', 1)[0])
                is_original = '-' not in strand_id

            current = representative.get(group)
            if current is None:
                group_order.append(group)
                keep = True
            elif is_original and not representative_is_original[group]:
                # The original instance after a transformed one. The PDB's files list it first,
                # but there is no reason to depend on that.
                collect[current] = False
                del residues[current]
                keep = True
            else:
                keep = False

            if keep:
                representative[group] = asym_id
                representative_is_original[group] = is_original
                strand_of[asym_id] = strand_id
                residues[asym_id] = {}
            collect[asym_id] = keep

        if not keep or pdb_mon_id in UNOBSERVED:
            continue

        chain_residues = residues[asym_id]
        number = int(seq_id)
        if number not in chain_residues:
            if residue_ids:
                pdb_seq_num, ins_code = residue
                chain_residues[number] = (_ONE_LETTER.get(mon_id, 'X'), pdb_seq_num if ins_code in UNOBSERVED else f'{pdb_seq_num}{ins_code}')
            else:
                chain_residues[number] = _ONE_LETTER.get(mon_id, 'X')

    stats.copies_skipped += stats.protein_instances - len(group_order)

    chains: dict[str, str] = {}
    for group in group_order:
        asym_id = representative[group]
        strand_id = strand_of[asym_id]
        if not is_valid_chain_name(strand_id):
            stats.unnamed += 1
            continue
        if strand_id in chains:
            stats.duplicate_names += 1
            continue
        chain_residues = residues[asym_id]
        if residue_ids:
            ordered = [chain_residues[number] for number in sorted(chain_residues)]
            chains[strand_id] = (''.join([letter for letter, _ in ordered]),
                                 {res_id: pos for pos, (_, res_id) in enumerate(ordered, 1)})
        else:
            chains[strand_id] = ''.join([chain_residues[number] for number in sorted(chain_residues)])

    return chains, stats


def get_observed_protein_chains(extract: CategoryExtract, residue_ids: bool = False) -> tuple[dict, ChainSelectionStats]:
    """chain name -> observed one letter sequence, for the protein chains of an assembly file.

    With residue_ids: chain name -> (sequence, {author residue id: sequence position}), see
    select_protein_chains.
    """
    entity_poly_lines = extract.categories.get('entity_poly')
    if entity_poly_lines is None:
        # No polymer at all (3irk is a single oligosaccharide).
        return {}, ChainSelectionStats(full_scan = extract.full_scan)

    entity_poly = parse_category('entity_poly', entity_poly_lines)
    if 'entity_id' not in entity_poly or 'type' not in entity_poly:
        raise MissingCategoryError('_entity_poly lacks entity_id or type')
    protein_entities = {
        entity_id for entity_id, poly_type in zip(category_column(entity_poly, 'entity_id'), category_column(entity_poly, 'type'))
        if poly_type == PROTEIN_POLY_TYPE
    }
    if not protein_entities:
        return {}, ChainSelectionStats(full_scan = extract.full_scan)

    poly_seq_lines = extract.categories.get('pdbx_poly_seq_scheme')
    if poly_seq_lines is None:
        raise MissingCategoryError('_pdbx_poly_seq_scheme is missing')

    remapping = _read_remapping(extract.categories.get('pdbx_chain_remapping'))
    columns = POLY_SEQ_RESIDUE_COLUMNS if residue_ids else POLY_SEQ_COLUMNS

    try:
        return select_protein_chains(
            iter_simple_loop_rows(poly_seq_lines, columns), protein_entities, remapping,
            ChainSelectionStats(full_scan = extract.full_scan), residue_ids = residue_ids,
        )
    except _NotASimpleLoop:
        return select_protein_chains(
            _biotite_rows('pdbx_poly_seq_scheme', poly_seq_lines, columns), protein_entities, remapping,
            ChainSelectionStats(full_scan = extract.full_scan, slow_path = True), residue_ids = residue_ids,
        )


def get_observed_protein_residues(extract: CategoryExtract) -> tuple[dict[str, tuple[str, dict[str, int]]], ChainSelectionStats]:
    """chain name -> (observed sequence, {author residue id: sequence position})."""
    return get_observed_protein_chains(extract, residue_ids = True)


OBSOLETE_SUBFOLDER = 'data/structures/obsolete/mmCIF'
# The deposited entries. Their header carries what the assembly files leave out: resolution,
# experimental method, references to sequence databases.
ENTRY_SUBFOLDER = 'data/structures/divided/mmCIF'


def obsolete_file_path(pdb_path: str, pdb_id: str) -> str:
    lower_id = pdb_id.lower()
    return f'{pdb_path}/{OBSOLETE_SUBFOLDER}/{lower_id[-3:-1]}/{lower_id}.cif.gz'


def entry_file_path(pdb_path: str, pdb_id: str) -> str:
    lower_id = pdb_id.lower()
    return f'{pdb_path.rstrip("/")}/{ENTRY_SUBFOLDER}/{lower_id[-3:-1]}/{lower_id}.cif.gz'


def read_obsolete_replacement(lines: Iterable[str]) -> str | None:
    """The entry that replaced an obsolete one (`_pdbx_database_PDB_obs_spr.pdb_id`), upper case.

    None when the entry was withdrawn without a successor. Several successors (a split entry)
    are listed separated by spaces in some files; the first is taken.
    """
    extract = extract_cif_categories(lines, ('pdbx_database_PDB_obs_spr',), stop_category = 'atom_site')
    category_lines = extract.categories.get('pdbx_database_PDB_obs_spr')
    if category_lines is None:
        return None
    category = parse_category('pdbx_database_PDB_obs_spr', category_lines)
    if 'pdb_id' not in category:
        return None
    ids = category_column(category, 'pdb_id')
    kinds = category_column(category, 'id') if 'id' in category else ['OBSLTE'] * len(ids)
    for kind, value in zip(kinds, ids):
        if kind == 'OBSLTE' and value not in UNOBSERVED:
            first = value.split()[0].strip(',')
            if first:
                return first.upper()
    return None


def read_assembly_protein_chains(path: str) -> tuple[dict[str, str], ChainSelectionStats]:
    return get_observed_protein_chains(read_cif_categories(path))
