# Cutting categories out of a file

@dataclass
class CategoryLines:
    """The raw lines of one category, in file order, without comments and blank lines."""
    is_loop: bool
    lines: list[str] = field(default_factory=list)
    # For a loop: how many of the leading lines are its tags. The data rows follow them.
    n_tag_lines: int = 0

    def body(self) -> str:
        """The category's text, with its `loop_` line if it is a loop."""
        return ''.join(['loop_\n' if self.is_loop else '', *self.lines])

    def to_cif(self) -> str:
        """The category as a CIF block of its own, the form biotite can parse."""
        return 'data_extract\n' + self.body()


@dataclass
class CategoryExtract:
    categories: dict[str, CategoryLines]
    # True when the stop category came before all required categories and the remainder of the
    # file had to be read. Expected only for files without any polymer.
    full_scan: bool = False
    # The first tag line of the stop category when reading stopped there. The caller can go on
    # reading that category from the same line iterator.
    stop_line: str | None = None


def extract_cif_categories(
        lines: Iterable[str],
        wanted: Iterable[str],
        required: Iterable[str] = (),
        stop_category: str | None = 'atom_site') -> CategoryExtract:
    """Collect the lines of the wanted categories of a single block CIF file.

    Stops when the category named `stop_category` begins, provided all `required` categories
    have been seen by then; otherwise it reads on to the end. Category names are compared
    exactly, so '_atom_sites.' or '_atom_site_anisotrop.' do not stop it. Lines inside a `;`
    text field are never taken for tags or keywords.
    """
    wanted = frozenset(wanted)
    missing_required = set(required)
    categories: dict[str, CategoryLines] = {}

    current_name: str | None = None
    current: CategoryLines | None = None
    loop_pending = False      # 'loop_' seen, its first tag not yet
    in_loop_tags = False      # between the first tag of a loop and its first value
    in_text_field = False
    full_scan = False
    seen_block = False
    stop_line = None

    for line in lines:
        if in_text_field:
            if current is not None:
                current.lines.append(line)
            if line.startswith(';'):
                in_text_field = False
            continue

        if line.startswith(';'):
            in_text_field = True
            in_loop_tags = False
            if current is not None:
                current.lines.append(line)
            continue

        stripped = line.strip()
        if not stripped or stripped[0] == '#':
            continue

        if stripped[0] == '_':
            name = stripped.split(None, 1)[0][1:].split('.', 1)[0]
            if loop_pending or name != current_name:
                if name == stop_category and not full_scan:
                    if not missing_required:
                        stop_line = line
                        break
                    full_scan = True
                if name in categories:
                    raise ValueError(f'Category _{name} occurs twice')
                current_name = name
                if name in wanted:
                    current = CategoryLines(is_loop=loop_pending)
                    categories[name] = current
                    missing_required.discard(name)
                else:
                    current = None
                in_loop_tags = loop_pending
                loop_pending = False
            if current is not None:
                current.lines.append(line)
                if in_loop_tags:
                    current.n_tag_lines += 1
            continue

        if stripped.lower() == 'loop_':
            loop_pending = True
            in_loop_tags = False
            current_name = None
            current = None
            continue

        if stripped.startswith('data_'):
            # Our files hold a single block. A second one is not read into the first.
            if seen_block:
                break
            seen_block = True
            continue

        # A value: a data row of a loop, or the value of a single item on the line below its tag.
        in_loop_tags = False
        if current is not None:
            current.lines.append(line)

    return CategoryExtract(categories = categories, full_scan = full_scan, stop_line = stop_line)


def open_cif_text(path: str):
    if path.endswith('.zst'):
        import zstandard
        return io.TextIOWrapper(zstandard.ZstdDecompressor().stream_reader(open(path, 'rb'), closefd = True),
                                encoding = 'utf-8', errors = 'replace')
    if path.endswith('.gz'):
        # The PDB's files are ASCII, but a stray byte in a category nobody reads must not cost
        # the whole file.
        return gzip.open(path, 'rt', encoding = 'utf-8', errors = 'replace')
    return open(path, 'r', encoding = 'utf-8', errors = 'replace')


def read_cif_categories(
        path: str,
        wanted: Iterable[str] = SEQUENCE_CATEGORIES,
        required: Iterable[str] = REQUIRED_SEQUENCE_CATEGORIES,
        stop_category: str | None = 'atom_site') -> CategoryExtract:
    with open_cif_text(path) as f:
        return extract_cif_categories(f, wanted, required = required, stop_category = stop_category)


# ---------------------------------------------------------------------------------------------
# Category parsing

def parse_category(name: str, category_lines: CategoryLines):
    """The category as a biotite CIFCategory."""
    # Imported here: biotite is only needed once a file is actually parsed.
    from biotite.structure.io import pdbx
    block = pdbx.CIFFile.read(io.StringIO(category_lines.to_cif())).block
    return block[name]


def category_column(category, column_name: str) -> list[str]:
    """The values of a column as str, with '?' and '.' for the missing and inapplicable ones."""
    column = category[column_name]
    values = column.as_array(str).tolist()
    mask = column.mask
    if mask is not None:
        # 0 present, 1 inapplicable ('.'), 2 missing ('?') - biotite's MaskValue
        for pos, flag in enumerate(mask.array.tolist()):
            if flag == 1:
                values[pos] = '.'
            elif flag == 2:
                values[pos] = '?'
    return values


class _NotASimpleLoop(Exception):
    pass


def iter_simple_loop_rows(category_lines: CategoryLines, columns: tuple[str, ...]) -> Iterator[tuple[str, ...]]:
    """The rows of a loop whose rows are one line each of plain whitespace separated tokens.

    Raises _NotASimpleLoop - possibly after rows have already been yielded - as soon as the loop
    turns out not to be of that form: quoted values, text fields, rows spread over several lines.
    """
    if not category_lines.is_loop:
        raise _NotASimpleLoop()

    tags = [line.strip().split('.', 1)[1] for line in category_lines.lines[:category_lines.n_tag_lines]]
    positions = {tag: pos for pos, tag in enumerate(tags)}
    missing = [column for column in columns if column not in positions]
    if missing:
        raise MissingCategoryError(f'Loop lacks the columns {missing}')

    n_tags = len(tags)
    pick = operator.itemgetter(*(positions[column] for column in columns))

    for line in category_lines.lines[category_lines.n_tag_lines:]:
        if '"' in line or "'" in line or line.startswith(';'):
            raise _NotASimpleLoop()
        parts = line.split()
        if len(parts) != n_tags:
            raise _NotASimpleLoop()
        yield pick(parts)


def _biotite_rows(name: str, category_lines: CategoryLines, columns: tuple[str, ...]) -> Iterator[tuple[str, ...]]:
    category = parse_category(name, category_lines)
    missing = [column for column in columns if column not in category]
    if missing:
        raise MissingCategoryError(f'_{name} lacks the columns {missing}')
    return zip(*(category_column(category, column) for column in columns))


