"""Reading PDB mmCIF files - for now the biological assembly files of the local PDB mirror.

The assembly files live in `<pdb_path>/data/assemblies/mmCIF/divided/<xx>/<id>-assembly<N>.cif.gz`.
They are generated by the PDB and differ from the entry files in ways that matter here:

- the block is `data_XXXX` and `_entry.id` is `XXXX`, so the PDB id only exists in the file name;
- there is one model per file, NMR entries included;
- chains created by a symmetry operator get the operator appended to their name (`A-2`, `C-59`,
  `A-12-86` for a product of operators). An original chain that only occurs transformed has no
  unsuffixed instance at all (7pth-assembly1 holds B, D, C-2 and A-3). `_pdbx_chain_remapping`
  maps every assembly chain back to the chain of the deposited entry it was made from.

Identifiers. An assembly is identified the way the RCSB does it, `<PDBID>-<assembly nr>`
(`1A04-2`), and a chain of it as `<assembly id>:<auth_asym_id>` (`1A04-2:B`, `2A0F-1:A-2`). A
chain id may contain '-' but never ':', ',', '_', ';' or whitespace, so ':' separates the two
unambiguously. Every place that builds or splits these ids should go through the helpers below.

Sequences. Only the categories that precede `_atom_site` are needed for the sequences of the
chains: `_entity_poly` (which entities are proteins), `_pdbx_poly_seq_scheme` (every residue of
every polymer chain of the assembly, unobserved ones marked by `?` in `pdb_mon_id`) and
`_pdbx_chain_remapping`. In the PDB's files they all come before `_atom_site`, which together with
`_atom_site_anisotrop` makes up the bulk of a file, so reading stops there. The observed sequence
derived from `_pdbx_poly_seq_scheme` was checked against the one derived from `_atom_site` and
matched for every protein chain of the sampled files.

biotite parses the small categories. It cannot be handed the raw head of a file: it needs a
`data_` line, fails on a trailing `loop_`, and splits categories at lines that start with '_' even
inside a `;` text field. `extract_cif_categories` therefore cuts out the wanted categories itself
and hands biotite a clean block. `_pdbx_poly_seq_scheme` is not given to biotite at all when it
can be avoided: in the largest assemblies it is a hundred MB of text (1m4x: 5040 chains, 2.08M
rows), which biotite turns into ~2 GB of Python strings. Its rows are plain whitespace separated
tokens, so they are split directly, and only a loop that does not look like that goes to biotite.
"""

from __future__ import annotations

import gzip
import io
import operator
import re
from collections.abc import Iterable, Iterator
from dataclasses import dataclass, field

from structman.base_utils.residue_consts import THREE_TO_ONE


ASSEMBLY_SUBFOLDER = 'data/assemblies/mmCIF/divided'

# 4 character ids today; the extended ids the wwPDB will hand out once those run out are
# pdb_ followed by 8 characters. Assembly numbers start at 1. Anything else in the folder - rsync's
# temporary '.1abc-assembly1.cif.gz.XyZ12' files during a sync, for instance - is not a match.
ASSEMBLY_FILE_RE = re.compile(r'^(?P<pdb>[0-9][a-z0-9]{3}|pdb_[0-9a-z]{8})-assembly(?P<nr>[1-9][0-9]*)\.cif\.gz$')
_ASSEMBLY_ID_RE = re.compile(r'^(?P<pdb>[0-9][A-Z0-9]{3}|PDB_[0-9A-Z]{8})-(?P<nr>[1-9][0-9]*)$')

# Characters that separate ids in the search DB headers and in the strings built from them later.
_FORBIDDEN_CHAIN_CHARACTERS = frozenset(':,_; \t\r\n')

PROTEIN_POLY_TYPE = 'polypeptide(L)'
UNOBSERVED = frozenset(('?', '.'))

SEQUENCE_CATEGORIES = ('entity_poly', 'pdbx_poly_seq_scheme', 'pdbx_chain_remapping')
REQUIRED_SEQUENCE_CATEGORIES = ('entity_poly', 'pdbx_poly_seq_scheme')
POLY_SEQ_COLUMNS = ('asym_id', 'entity_id', 'seq_id', 'mon_id', 'pdb_mon_id', 'pdb_strand_id')
# The author residue numbering (as in _atom_site.auth_seq_id / pdbx_PDB_ins_code), for the
# residue ids of PDB inputs.
POLY_SEQ_RESIDUE_COLUMNS = POLY_SEQ_COLUMNS + ('pdb_seq_num', 'pdb_ins_code')
_REMAP_COLUMNS = ('label_asym_id', 'auth_asym_id', 'orig_label_asym_id', 'orig_auth_asym_id')

# THREE_TO_ONE maps a few chromophores to several letters (CRO -> GYG); like the PDB format
# parsers, only the first one is used.
_ONE_LETTER: dict[str, str] = {three: one[0] for three, one in THREE_TO_ONE.items() if one}


class MissingCategoryError(ValueError):
    pass


# ---------------------------------------------------------------------------------------------
# File names and identifiers

def assembly_divided_folder(pdb_path: str) -> str:
    return f'{pdb_path.rstrip("/")}/{ASSEMBLY_SUBFOLDER}'


def parse_assembly_filename(filename: str) -> tuple[str, int] | None:
    """('1A04', 2) for '1a04-assembly2.cif.gz', None for anything that is not an assembly file."""
    match = ASSEMBLY_FILE_RE.match(filename)
    if match is None:
        return None
    return match.group('pdb').upper(), int(match.group('nr'))


def assembly_file_path(pdb_path: str, pdb_id: str, assembly_nr: int) -> str:
    # The divided folder is named after the two characters in front of the last one: the middle
    # of a 4 character id. For extended ids the same rule is an assumption until the wwPDB
    # actually ships them.
    lower_id = pdb_id.lower()
    return f'{assembly_divided_folder(pdb_path)}/{lower_id[-3:-1]}/{lower_id}-assembly{assembly_nr}.cif.gz'


def make_assembly_id(pdb_id: str, assembly_nr: int) -> str:
    return f'{pdb_id.upper()}-{assembly_nr}'


def split_assembly_id(structure_id: str) -> tuple[str, int]:
    match = _ASSEMBLY_ID_RE.match(structure_id)
    if match is None:
        raise ValueError(f'Not an assembly id: {structure_id!r}')
    return match.group('pdb'), int(match.group('nr'))


def is_assembly_id(structure_id: str) -> bool:
    return _ASSEMBLY_ID_RE.match(structure_id) is not None


def is_valid_chain_name(chain: str) -> bool:
    if not chain or chain in UNOBSERVED:
        return False
    return not any(character in _FORBIDDEN_CHAIN_CHARACTERS for character in chain)


def make_chain_id(structure_id: str, chain: str) -> str:
    return f'{structure_id}:{chain}'


def split_chain_id(chain_id: str) -> tuple[str, str]:
    structure_id, separator, chain = chain_id.partition(':')
    if not separator or not structure_id or not chain:
        raise ValueError(f'Not a chain id: {chain_id!r}')
    return structure_id, chain


def is_assembly_chain_id(chain_id: str) -> bool:
    """1A04-2:B, 2A0F-1:A-2 - a chain of a PDB assembly, as the search DB names it."""
    structure_id, separator, chain = chain_id.partition(':')
    return bool(separator) and is_assembly_id(structure_id) and is_valid_chain_name(chain)


# Sets of chains as strings (Structure_N.Homooligomer, Complex.Homooligomers). Chain names never
# contain ',' or ';', so chains are joined by ',' and groups of chains by ';'.

def join_chains(chains) -> str:
    return ','.join(chains)


def split_chains(text: str | None) -> list[str]:
    if not text:
        return []
    return [chain for chain in text.split(',') if chain]


def join_chain_groups(groups) -> str:
    return ';'.join(join_chains(group) for group in groups)


def split_chain_groups(text: str | None) -> list[list[str]]:
    if not text:
        return []
    return [split_chains(group) for group in text.split(';') if group]


# The partner chain of an interface (Structure_N.Interacting_Residue_Data). A symmetry copy has no
# Structure of its own: it is named together with the kept chain it copies, '<copy>;<kept chain>',
# and its residues are numbered as in that kept chain.

def make_partner_chain(chain: str, original: str | None = None) -> str:
    return chain if original is None else f'{chain};{original}'


def split_partner_chain(name: str) -> tuple[str, str]:
    """(partner chain, the chain whose structure holds its residues)."""
    chain, separator, original = name.partition(';')
    return chain, original if separator else chain


